// 网络错误按代码翻译;检测器自己抛的错已经是对应语言
export function errText(t, err) {
  if (err?.code === "http") return t("errHttp", err.status);
  if (err?.code === "timeout") return t("errTimeout");
  if (err?.code === "network") return t("errNetwork");
  return err?.message || t("errNetwork");
}
