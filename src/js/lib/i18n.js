export function makeT(lang) {
  const d = STR[lang];
  if (!d) throw new Error(`unknown language: ${lang}`);
  return (key, ...args) => {
    const v = d[key];
    if (v === undefined) throw new Error(`missing text: ${lang}.${key}`);
    return typeof v === "function" ? v(...args) : v;
  };
}

