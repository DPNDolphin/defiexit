// Формы после числа: 1, 21, 31… / 2–4, 22–24… / остальные (0, 5–20, 25…)
const pl = (n, one, few, many) => {
  const a = Math.abs(n) % 100, b = a % 10;
  return a > 10 && a < 20 ? many : b === 1 ? one : b >= 2 && b <= 4 ? few : many;
};
